"""Write `docs/EVENTS.md`: every event type Clank declares, with what it means, its data, whether it is kept, and
whether its events need the owner's attention (decision 0113).

Generated from the declarations (`clank.registry.event_types()`), never edited by hand, and checked by a test, so the
page and the code cannot disagree (design 0002 §2.3).
"""

import sys
from pathlib import Path

from clank import registry
from clank.kernel.events import EventTypes
from tools.generated import write_or_check

OUTPUT = Path("docs/EVENTS.md")
COMMAND = "uv run python -m tools.eventsdoc"
HEADER = """\
# Events

Generated by `python -m tools.eventsdoc` from the event types each part of Clank declares; do not edit it by hand.
Every event has an id (a number that only grows), its time, its type, the record it concerns, who caused it, a
one-line summary and the data below (design 0002 §2.3). Kept events are the history; live-only events reach the
clients as they happen and are never kept. An event of a type that "needs you" carries `attention` (decision 0113): a
client may notify the owner of it, its summary the title.
"""


def render(types: EventTypes) -> str:
    """The events page for a set of declared types, grouped by the part that declares them."""
    parts = [HEADER]
    owner = None
    for event_type in types.all():
        if event_type.owner != owner:
            owner = event_type.owner
            parts.append(f"\n## {owner}\n\n| Type | Kept | What it means | Data |\n| --- | --- | --- | --- |\n")
        data = "; ".join(f"`{name}`: {help}" for name, help in event_type.fields.items()) or "none"
        kept = ("live only" if event_type.live else "kept") + (", needs you" if event_type.attention else "")
        parts.append(f"| `{event_type.name}` | {kept} | {event_type.help} | {data} |\n")
    if owner is None:
        parts.append("\nNo event type is declared yet.\n")
    return "".join(parts)


def render_repository() -> str:
    """The events page for everything Clank declares."""
    return render(registry.event_types())


def main(argv: list[str] | None = None) -> int:
    """Write the events page, or with `--check` only report whether it is up to date; returns the exit status."""
    args = sys.argv[1:] if argv is None else argv
    root = Path(__file__).resolve().parents[1]
    return write_or_check(root / OUTPUT, render_repository(), check="--check" in args, command=COMMAND)


if __name__ == "__main__":
    sys.exit(main())
