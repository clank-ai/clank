"""Write `docs/TESTS.md`: each section of each design, with the test files that hold it to its word.

Each test file begins with a docstring naming the design sections it verifies, such as "Design 0002 §3.2" (design 0001
§8.5); a TypeScript test file of the VS Code extension (`vscode/test/*.test.ts`) begins with a comment that does the
same, and its tests are named in sentences (`test("a question fits its type", ...)`). This module reads those and the
designs' numbered headings, so the page shows which sections have
tests and which have none yet. A test file that names no section, or names a section that no design has, is an error,
so the references stay true when a design changes.

A reference may name a list of sections of one design ("Design 0011 §4, §8 and §11": the file is listed under each)
and may break across lines anywhere a space stands. A range ("§6.1-§6.5") counts for its first section only: name each
section, in a list, for the page to list the file under all of them.
"""

import ast
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

from tools.files import repository_files
from tools.generated import write_or_check
from tools.markdown import prose_lines

OUTPUT = Path("docs/TESTS.md")
COMMAND = "uv run python -m tools.testspage"
SECTION = r"§(\d+(?:\.\d+)*)"  # "§3.2", never the period that ends a sentence after it
LISTED = r"§\d+(?:\.\d+)*(?:(?:\s*,\s*(?:and\s+)?|\s+and\s+)§\d+(?:\.\d+)*)*"  # "§4", "§4 and §8", "§4, §8, and §11"
REFERENCE = re.compile(rf"design\s+(\d{{4}})\s+({LISTED})", re.IGNORECASE)
TEST_FILE = re.compile(r"^test_.*\.py$")
TYPESCRIPT_TEST = re.compile(r'^\s*test\(\s*"([^"]+)"', re.MULTILINE)
TITLE = re.compile(r"^# Design (\d{4}): (.+)$")
HEADING = re.compile(r"^#{2,3} (\d+(?:\.\d+)?)\.? (.+)$")
HEADER = """\
# Tests

Generated by `python -m tools.testspage` from the tests' docstrings and the designs' headings; do not edit it by hand.
Each test file begins with a docstring naming the design sections it verifies (design 0001 §8.5).
"""


class PageError(Exception):
    """Test files the page cannot place: naming no design section, or a section that does not exist."""


@dataclass
class Section:
    """A numbered section of a design document, and the test files that name it."""

    design: str
    number: str
    title: str
    files: list[str] = field(default_factory=list)


@dataclass
class FileOfTests:
    """A test file: what its docstring says it proves, the sections it names, and its tests' names as sentences."""

    path: str
    summary: str
    references: list[tuple[str, str]]
    tests: list[str]


def designs(root: Path) -> dict[str, tuple[str, list[Section]]]:
    """Each design's title and numbered sections, in document order, keyed by the design's number."""
    found: dict[str, tuple[str, list[Section]]] = {}
    for path in sorted((root / "docs" / "design").glob("[0-9][0-9][0-9][0-9]-*.md")):
        design = path.name[:4]
        title = path.stem
        sections: list[Section] = []
        for _, line in prose_lines(path.read_text(encoding="utf-8")):
            if match := TITLE.match(line):
                title = match.group(2)
            elif match := HEADING.match(line):
                sections.append(Section(design, match.group(1), match.group(2).strip()))
        found[design] = (title, sections)
    return found


def references_in(text: str) -> list[tuple[str, str]]:
    """Each (design, section) a docstring or comment names, in order: "Design 0011 §4 and §8" gives ("0011", "4") and
    ("0011", "8")."""
    return [
        (match.group(1), number) for match in REFERENCE.finditer(text) for number in re.findall(SECTION, match.group(2))
    ]


def sentence(name: str) -> str:
    """A test's name as the sentence it is: `test_a_switch_returns` becomes "a switch returns"."""
    return name.removeprefix("test_").replace("_", " ")


def files_of_tests(root: Path) -> list[FileOfTests]:
    """Every test file under `tests/`, with the sections its docstring names and its tests' names."""
    found: list[FileOfTests] = []
    files = [root / path for path in repository_files(root)]
    for path in (path for path in files if path.relative_to(root).parts[0] == "tests" and TEST_FILE.match(path.name)):
        name = path.relative_to(root).as_posix()
        tree = ast.parse(path.read_text(encoding="utf-8"), filename=name)
        doc = ast.get_docstring(tree) or ""
        summary = " ".join(doc.split("\n\n")[0].split())
        found.append(FileOfTests(name, summary, references_in(doc), [sentence(test) for test in _test_names(tree)]))
    typescript = root / "vscode" / "test"
    for path in (path for path in files if path.is_relative_to(typescript) and path.name.endswith(".test.ts")):
        text = path.read_text(encoding="utf-8")
        comment = _leading_comment(text)
        summary = " ".join(comment.split("\n\n")[0].split())
        name = path.relative_to(root).as_posix()
        found.append(FileOfTests(name, summary, references_in(comment), TYPESCRIPT_TEST.findall(text)))
    return found


def _leading_comment(text: str) -> str:
    """The comment lines a TypeScript file begins with, without their slashes; an empty one starts a new paragraph."""
    lines = []
    for line in text.lstrip().splitlines():
        if not line.startswith("//"):
            break
        lines.append(line[2:].strip())
    return "\n".join(line if line else "\n" for line in lines)


def _test_names(tree: ast.Module) -> list[str]:
    """The names of a module's tests: its `test` functions, and those of its `Test` classes."""
    names: list[str] = []
    for node in tree.body:
        if isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef) and node.name.startswith("test"):
            names.append(node.name)
        elif isinstance(node, ast.ClassDef) and node.name.startswith("Test"):
            names.extend(
                child.name
                for child in node.body
                if isinstance(child, ast.FunctionDef | ast.AsyncFunctionDef) and child.name.startswith("test")
            )
    return names


def _has_subsections(section: Section, sections: list[Section]) -> bool:
    return any(other.number.startswith(section.number + ".") for other in sections)


def render(root: Path) -> str:
    """The tests page of the repository at `root`; raises PageError naming every test file it cannot place."""
    known = designs(root)
    index = {(design, section.number): section for design, (_, sections) in known.items() for section in sections}
    files = files_of_tests(root)
    problems: list[str] = []
    for entry in files:
        if not entry.references:
            problems.append(f'{entry.path}: its docstring names no design section (as in "Design 0002 §3.2")')
        for design, number in entry.references:
            section = index.get((design, number))
            if section is None:
                problems.append(f"{entry.path}: names design {design} §{number}, which does not exist")
            elif entry.path not in section.files:
                section.files.append(entry.path)
    if problems:
        raise PageError("\n".join(problems))
    counts = {entry.path: len(entry.tests) for entry in files}
    leaves = [s for _, sections in known.values() for s in sections if not _has_subsections(s, sections)]
    covered = sum(1 for section in leaves if section.files)
    out = [
        HEADER,
        f"\n**{covered} of {len(leaves)} design sections have tests.** "
        "A section with subsections is covered through them.\n",
    ]
    for design, (title, sections) in known.items():
        out.append(f"\n## Design {design}: {title}\n\n| § | Section | Tests |\n| --- | --- | --- |\n")
        for section in sections:
            if section.files:
                cell = ", ".join(f"`{path}` ({counts[path]})" for path in section.files)
            elif _has_subsections(section, sections):
                cell = "see its subsections"
            else:
                cell = "none yet"
            name = section.title.replace("|", "\\|")
            out.append(f"| {section.number} | {name} | {cell} |\n")
    out.append("\n## Test files\n")
    for entry in files:
        out.append(f"\n### `{entry.path}`\n\n{entry.summary}\n\n")
        out.extend(f"- {test}\n" for test in entry.tests)
    return "".join(out)


def main(argv: list[str] | None = None) -> int:
    """Write the tests page, or with `--check` only report whether it is up to date; returns the exit status."""
    args = sys.argv[1:] if argv is None else argv
    root = Path(__file__).resolve().parents[1]
    try:
        text = render(root)
    except PageError as error:
        print(error, file=sys.stderr)
        return 1
    return write_or_check(root / OUTPUT, text, check="--check" in args, command=COMMAND)


if __name__ == "__main__":
    sys.exit(main())
