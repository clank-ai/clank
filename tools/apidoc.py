"""Write `docs/API.md`: every route of the Clank API, with its method, path, access level and what it does.

Generated from the application itself (design 0002 §2.14), built over a throwaway CLANK_HOME, so the page lists exactly
the routes the service serves, the components' included; a test fails when it is out of date.
"""

import sys
import tempfile
from pathlib import Path

from fastapi import FastAPI

from clank import registry
from clank.kernel.api import access_of, create_app
from clank.kernel.clock import SystemClock
from clank.kernel.core import open_kernel
from clank.kernel.home import Home
from tools.generated import write_or_check

OUTPUT = Path("docs/API.md")
COMMAND = "uv run python -m tools.apidoc"
HEADER = """\
# API

Generated by `python -m tools.apidoc` from the Clank API itself; do not edit it by hand. Every route is under
`http://127.0.0.1:<port>/api/v1/` and needs the local token (`Authorization: Bearer <token>`, from
`CLANK_HOME/state/local.token`); a client names itself in `X-Clank-Client`. Errors have one shape:
`{"error": {"code", "message", "where"}}` (design 0002 §2.14). The full description is `GET /api/v1/openapi.json`.

| Method | Path | Access | What it does |
| --- | --- | --- | --- |
"""


def render(app: FastAPI) -> str:
    """The API page of an application."""
    rows = []
    for path, methods in app.openapi()["paths"].items():
        for method, operation in methods.items():
            description = (operation.get("description") or "").strip().splitlines()
            what = description[0] if description else ""
            rows.append((path, method.upper(), access_of(operation) or "none", what))
    rows.sort()
    return HEADER + "".join(f"| {method} | `{path}` | {access} | {what} |\n" for path, method, access, what in rows)


def render_repository(scratch: Path) -> str:
    """The API page of the service as Clank declares it, built over a CLANK_HOME under `scratch`."""
    kernel = open_kernel(Home(scratch / "home"), SystemClock(), registry.components())
    try:
        return render(create_app(kernel, token="unused", port=7720))
    finally:
        kernel.close()


def main(argv: list[str] | None = None) -> int:
    """Write the API page, or with `--check` only report whether it is up to date; returns the exit status."""
    args = sys.argv[1:] if argv is None else argv
    root = Path(__file__).resolve().parents[1]
    with tempfile.TemporaryDirectory() as scratch:
        text = render_repository(Path(scratch))
    return write_or_check(root / OUTPUT, text, check="--check" in args, command=COMMAND)


if __name__ == "__main__":
    sys.exit(main())
