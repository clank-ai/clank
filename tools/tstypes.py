"""Write `vscode/src/core/kinds.ts`: the TypeScript types of Clank's kinds of record (decisions 0015, 0028).

Each kind's JSON Schema (Pydantic's, for serialization) becomes one TypeScript interface named after its class, with
every field present, as the API always sends records whole, and each definition the kinds use becomes one more,
written once; every field keeps its description as a comment. `RecordsByKind` maps each kind's name to its interface.
The mapping covers what Clank's schemas use: strings (date-times included), numbers, booleans, `null`, literal
choices, arrays, maps, nested objects and references to definitions; anything else is `unknown`. Never edited by hand:
`tools.check --fix` writes it again, and a test fails when it is out of date.
"""

import json
import sys
from collections.abc import Iterable
from pathlib import Path
from typing import Any

from clank import registry

OUTPUT = Path("vscode/src/core/kinds.ts")
COMMAND = "uv run python -m tools.tstypes"
HEAD = """// The TypeScript types of Clank's kinds of record, as the API sends them (decisions 0015, 0028).
// Generated by `uv run python -m tools.tstypes` from each kind's one definition: never edit this file by hand.
"""


def typescript_of(schema: dict[str, Any]) -> str:
    """The TypeScript type of a JSON Schema."""
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(choice) for choice in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(typescript_of(choice) for choice in schema["anyOf"])
    kind = schema.get("type")
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        items = typescript_of(schema.get("items", {}))
        return f"({items})[]" if " | " in items else f"{items}[]"
    if kind == "object":
        if "properties" in schema:
            required = set(schema.get("required", []))
            fields = [
                f"{name}{'' if name in required else '?'}: {typescript_of(field)}"
                for name, field in schema["properties"].items()
            ]
            return "{ " + "; ".join(fields) + " }"
        values = schema.get("additionalProperties", True)
        return f"Record<string, {typescript_of(values) if isinstance(values, dict) else 'unknown'}>"
    return "unknown"


def interface(name: str, schema: dict[str, Any]) -> str:
    """One interface: the schema's description, then each field with its own, every one present (the API sends records
    whole)."""
    lines = []
    if schema.get("description"):
        lines.append(f"/** {_comment(schema['description'])} */")
    lines.append(f"export interface {name} {{")
    for field, body in schema.get("properties", {}).items():
        if body.get("description"):
            lines.append(f"  /** {_comment(body['description'])} */")
        lines.append(f"  {field}: {typescript_of(body)};")
    lines.append("}")
    return "\n".join(lines)


def render(kinds: Iterable[Any]) -> str:
    """The whole file, for these kinds."""
    blocks: list[str] = []
    definitions: dict[str, dict[str, Any]] = {}
    names: dict[str, str] = {}
    for kind in kinds:
        schema = kind.model_json_schema(mode="serialization")
        for name, definition in schema.get("$defs", {}).items():
            if name in definitions and definitions[name] != definition:
                raise ValueError(f"two different definitions are named {name}")
            definitions[name] = definition
        blocks.append(interface(kind.__name__, schema))
        names[kind.KIND] = kind.__name__
    blocks += [interface(name, definitions[name]) for name in sorted(definitions)]
    keys = {kind: kind if kind.isidentifier() else f'"{kind}"' for kind in names}
    mapping = ["export interface RecordsByKind {", *[f"  {keys[kind]}: {name};" for kind, name in names.items()], "}"]
    return HEAD + "\n" + "\n\n".join([*blocks, "\n".join(mapping)]) + "\n"


def render_repository() -> str:
    """The file for every kind Clank declares."""
    return render(registry.kinds().all())


def main() -> int:
    """Write the file."""
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_bytes(render_repository().encode("utf-8"))
    return 0


def _comment(text: str) -> str:
    return " ".join(str(text).split()).replace("*/", "* /")


if __name__ == "__main__":
    sys.exit(main())
