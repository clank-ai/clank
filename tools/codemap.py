"""Write `docs/CODEMAP.md`: one line per module of `clank/`, `tools/` and the VS Code extension (`vscode/src/`,
`vscode/test/`): the first line of a Python module's docstring, or of a TypeScript module's leading comment.

A reader, a person or a local model with a small context, finds where a thing lives without opening the code. The map
is generated, never edited by hand, and a test fails when it is out of date (`tests/test_repository.py`). A module
without a docstring (or a leading comment) is an error: every module says what it is for (AGENTS.md).
"""

import ast
import sys
from pathlib import Path

from tools.files import repository_files
from tools.generated import write_or_check

ROOTS = ("clank", "tools", "vscode")
TYPESCRIPT = ("vscode/src", "vscode/test", "vscode/host")
OUTPUT = Path("docs/CODEMAP.md")
COMMAND = "uv run python -m tools.codemap"
HEADER = """\
# Code map

Generated by `python -m tools.codemap` from each module's docstring; do not edit it by hand. One line per module: what
it is for. The module's docstring says why it is built the way it is.
"""


class CodeMapError(Exception):
    """Modules the code map cannot describe: without a docstring, or not valid Python."""


def modules(root: Path) -> list[Path]:
    """Every module under the code map's roots that git tracks or would track, relative to `root`, in a stable order."""
    files = repository_files(root)
    found = [path for path in files if path.suffix == ".py" and path.parts[0] in ROOTS[:2]]
    found += [path for path in files if path.suffix == ".ts" and path.parent.as_posix().startswith(TYPESCRIPT)]
    return sorted(found, key=lambda path: path.as_posix())


def summary(root: Path, module: Path) -> str:
    """The first line of the module's docstring (a TypeScript module's leading comment); raises CodeMapError when there
    is none."""
    name = module.as_posix()
    if module.suffix == ".ts":
        first = (root / module).read_text(encoding="utf-8").lstrip().splitlines()[:1]
        if not first or not first[0].startswith("//") or not first[0].strip("/ "):
            raise CodeMapError(f"{name}: has no leading comment; its first line must say what the module is for")
        return first[0].strip("/ ").strip()
    try:
        tree = ast.parse((root / module).read_text(encoding="utf-8"), filename=name)
    except (SyntaxError, UnicodeDecodeError) as error:
        raise CodeMapError(f"{name}: cannot be read as Python ({error})") from error
    doc = ast.get_docstring(tree)
    if not doc or not doc.strip():
        raise CodeMapError(f"{name}: has no docstring; its first line must say what the module is for")
    return doc.strip().splitlines()[0].strip()


def render(root: Path) -> str:
    """The code map of the repository at `root`; raises CodeMapError naming every module it cannot describe."""
    rows: dict[str, list[str]] = {top: [] for top in ROOTS}
    problems: list[str] = []
    for module in modules(root):
        try:
            line = summary(root, module).replace("|", "\\|")
        except CodeMapError as error:
            problems.append(str(error))
            continue
        rows[module.parts[0]].append(f"| `{module.as_posix()}` | {line} |\n")
    if problems:
        raise CodeMapError("\n".join(problems))
    parts = [HEADER]
    for top in ROOTS:
        if not rows[top] and top not in ROOTS[:2]:
            continue
        parts.append(f"\n## {top}\n\n| Module | What it is for |\n| --- | --- |\n")
        parts.extend(rows[top])
    return "".join(parts)


def main(argv: list[str] | None = None) -> int:
    """Write the code map, or with `--check` only report whether it is up to date; returns the exit status."""
    args = sys.argv[1:] if argv is None else argv
    root = Path(__file__).resolve().parents[1]
    try:
        text = render(root)
    except CodeMapError as error:
        print(error, file=sys.stderr)
        return 1
    return write_or_check(root / OUTPUT, text, check="--check" in args, command=COMMAND)


if __name__ == "__main__":
    sys.exit(main())
